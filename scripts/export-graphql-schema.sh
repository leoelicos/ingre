#!/bin/sh
# #195: writes the server's GraphQL schema (server/src/schemas/typeDefs.ts) as SDL for the
# native apps' Apollo codegen. No server change: the SDL is read from typeDefs as-is. The
# server declares Query and Mutation more than once (graphql-tools merges them); plain SDL
# needs `extend type` for the repeats, which this adds. CI runs it with --check so the
# committed schema files never drift from the server.
# Usage: scripts/export-graphql-schema.sh [--check]
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
TYPEDEFS="$ROOT/server/src/schemas/typeDefs.ts"
TARGETS="$ROOT/ios/graphql/schema.graphqls $ROOT/android/app/src/main/graphql/schema.graphqls"
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
{
  echo "# Generated by scripts/export-graphql-schema.sh from server/src/schemas/typeDefs.ts (#195)."
  echo "# Do not edit by hand: run the script again after a schema change."
  awk '
    /gql`/ { inside = 1; next }
    inside && /^`/ { inside = 0; next }
    inside {
      line = $0
      sub(/^  /, "", line)
      if (match(line, /^type [A-Za-z_][A-Za-z0-9_]*/)) {
        name = substr(line, 6, RLENGTH - 5)
        if (seen[name]++) line = "extend " line
      }
      print line
    }
  ' "$TYPEDEFS"
} > "$TMP"
if [ "${1:-}" = "--check" ]; then
  status=0
  for target in $TARGETS; do
    if ! cmp -s "$TMP" "$target"; then
      echo "error: $target is out of date; run scripts/export-graphql-schema.sh" >&2
      status=1
    fi
  done
  exit $status
fi
for target in $TARGETS; do
  mkdir -p "$(dirname "$target")"
  cp "$TMP" "$target"
  echo "wrote $target"
done
